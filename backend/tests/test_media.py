def test_author_cannot_delete_after_48h_but_admin_can(
    client, worker_headers, admin_headers, obra, db_session
):
    from app.models import MediaFile

    item = upload(client, obra.id, worker_headers).json()[0]
    media = db_session.get(MediaFile, uuid.UUID(item["id"]))
    media.uploaded_at = utc_naive_days_ago(3)
    db_session.add(media)
    db_session.commit()

    res = client.delete(f"/api/v1/media/{item['id']}", headers=worker_headers)
    assert res.status_code == 403

    res = client.delete(f"/api/v1/media/{item['id']}", headers=admin_headers)
    assert res.status_code == 204


