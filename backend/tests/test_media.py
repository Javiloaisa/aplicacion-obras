import io
import uuid

from PIL import Image

from tests.test_entries import utc_naive_days_ago


def make_jpeg(width=64, height=48) -> bytes:
    buf = io.BytesIO()
    Image.new("RGB", (width, height), "red").save(buf, format="JPEG")
    return buf.getvalue()


def make_png() -> bytes:
    buf = io.BytesIO()
    Image.new("RGBA", (32, 32), (0, 255, 0, 255)).save(buf, format="PNG")
    return buf.getvalue()


# Valid EBML/WebM magic bytes followed by padding (ffmpeg-less test stub)
FAKE_WEBM = b"\x1a\x45\xdf\xa3" + b"\x00" * 256


def upload(client, obra_id, headers, filename="foto.jpg", content=None, caption=None):
    files = [("files", (filename, content if content is not None else make_jpeg(), "application/octet-stream"))]
    data = {}
    if caption is not None:
        data["caption"] = caption
    return client.post(
        f"/api/v1/obras/{obra_id}/media", files=files, data=data, headers=headers
    )


def test_upload_photo_creates_media_and_thumbnail(client, worker_headers, obra):
    res = upload(client, obra.id, worker_headers, caption="fachada")
    assert res.status_code == 201
    (item,) = res.json()
    assert item["kind"] == "photo"
    assert item["mime_type"] == "image/jpeg"
    assert item["original_filename"] == "foto.jpg"
    assert item["caption"] == "fachada"

    # Thumbnail generated by the background task right after the response
    res = client.get(f"/api/v1/media/{item['id']}/thumb", headers=worker_headers)
    assert res.status_code == 200
    assert res.headers["content-type"] == "image/jpeg"


