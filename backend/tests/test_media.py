def test_download_file_supports_range(client, worker_headers, obra):
    item = upload(
        client, obra.id, worker_headers, filename="video.webm", content=FAKE_WEBM
    ).json()[0]

    res = client.get(f"/api/v1/media/{item['id']}/file", headers=worker_headers)
    assert res.status_code == 200
    assert res.content == FAKE_WEBM

    res = client.get(
        f"/api/v1/media/{item['id']}/file",
        headers={**worker_headers, "Range": "bytes=0-9"},
    )
    assert res.status_code == 206
    assert len(res.content) == 10


