def test_author_edits_caption_other_worker_cannot(
    client, worker_headers, worker2_headers, admin_headers, obra, worker2
):
    item = upload(client, obra.id, worker_headers).json()[0]
    client.post(
        f"/api/v1/obras/{obra.id}/assignments",
        json={"add": [str(worker2.id)]},
        headers=admin_headers,
    )

    res = client.patch(
        f"/api/v1/media/{item['id']}", json={"caption": "nueva"}, headers=worker_headers
    )
    assert res.status_code == 200
    assert res.json()["caption"] == "nueva"

    res = client.patch(
        f"/api/v1/media/{item['id']}", json={"caption": "x"}, headers=worker2_headers
    )
    assert res.status_code == 403

    res = client.patch(
        f"/api/v1/media/{item['id']}", json={"caption": "admin"}, headers=admin_headers
    )
    assert res.status_code == 200


